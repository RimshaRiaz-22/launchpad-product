// ─── 4. SEEDER EXECUTION FUNCTION ─────────────────────────────────────────────
async function seedShapes() {
  console.log('🚀 Starting Precision Vector Shapes & Categories Seeding...');

  // 1. Ensure Asset Categories for Shapes
  console.log(`📂 Ensuring ${SHAPE_CATEGORIES.length} shape categories...`);
  for (const cat of SHAPE_CATEGORIES) {
    const existing = await db('asset_categories').where({ id: cat.id }).first();
    if (!existing) {
      await db('asset_categories').insert({
        ...cat,
        created_at: db.fn.now(),
        updated_at: db.fn.now(),
      });
      console.log(`   ➕ Inserted shape category: ${cat.name} (${cat.id})`);
    } else {
      await db('asset_categories')
        .where({ id: cat.id })
        .update({
          name: cat.name,
          label: cat.label,
          asset_type: cat.asset_type,
          description: cat.description,
          icon: cat.icon,
          color: cat.color,
          sort_order: cat.sort_order,
          is_active: cat.is_active,
          updated_at: db.fn.now(),
        });
    }
  }

  // 2. Ensure Subcategories for Shapes
  console.log(`📂 Ensuring ${SHAPE_SUBCATEGORIES.length} shape subcategories...`);
  for (const sub of SHAPE_SUBCATEGORIES) {
    const existing = await db('asset_subcategories').where({ id: sub.id }).first();
    if (!existing) {
      await db('asset_subcategories').insert({
        ...sub,
        is_active: true,
        created_at: db.fn.now(),
        updated_at: db.fn.now(),
      });
      console.log(`   ➕ Inserted shape subcategory: ${sub.name} (${sub.id})`);
    } else {
      await db('asset_subcategories')
        .where({ id: sub.id })
        .update({
          category_id: sub.category_id,
          name: sub.name,
          label: sub.label,
          sort_order: sub.sort_order,
          updated_at: db.fn.now(),
        });
    }
  }

  // 3. Upsert Shapes into `assets` table AND `shapes` table
  console.log(`✨ Upserting ${SHAPE_ASSETS.length} shapes into assets & shapes tables...`);
  let insertedCount = 0;
  let updatedCount = 0;

  const hasShapesTable = await db.schema.hasTable('shapes');

  for (const item of SHAPE_ASSETS) {
    const fileUrl = makeShapeSvg(item.svg_render);
    const existingAsset = await db('assets').where({ id: item.id }).first();

    const assetPayload = {
      id: item.id,
      name: item.name,
      type: 'shape',
      category: item.category,
      subcategory: item.subcategory,
      group_id: item.group_id,
      group_label: item.group_label,
      file_url: fileUrl,
      file_path: null,
      file_size: 1024,
      mime_type: 'image/svg+xml',
      width: 100,
      height: 100,
      is_builtin: true,
      is_premium: false,
      use_count: existingAsset ? existingAsset.use_count : 0,
      metadata: JSON.stringify({
        preview_type: item.preview_type,
        preview_data: item.preview_data,
        svg_path: item.svg_path,
        fabric_type: item.fabric_type,
        default_props: item.default_props,
        tags: item.tags,
      }),
      updated_at: db.fn.now(),
    };

    if (!existingAsset) {
      await db('assets').insert({
        ...assetPayload,
        created_at: db.fn.now(),
      });
      insertedCount++;
    } else {
      await db('assets').where({ id: item.id }).update(assetPayload);
      updatedCount++;
    }

    // Also sync to legacy/dedicated shapes table if present
    if (hasShapesTable) {
      const existingShape = await db('shapes').where({ id: item.id }).first();
      const shapePayload = {
        id: item.id,
        name: item.name,
        group_id: item.group_id,
        group_label: item.group_label,
        preview_type: item.preview_type,
        preview_data: JSON.stringify(item.preview_data),
        svg_path: item.svg_path,
        fabric_type: item.fabric_type,
        default_props: JSON.stringify(item.default_props),
        updated_at: db.fn.now(),
      };

      if (!existingShape) {
        await db('shapes').insert({
          ...shapePayload,
          created_at: db.fn.now(),
        });
      } else {
        await db('shapes').where({ id: item.id }).update(shapePayload);
      }
    }
  }

  // Invalidate memory cache so frontend immediately sees updated tree
  try {
    memoryCache.delPrefix('asset:categories');
  } catch (_) {}

  console.log(`✅ [Vector Shapes] Seeding completed successfully!`);
  console.log(`   - Shapes Inserted: ${insertedCount}`);
  console.log(`   - Shapes Updated:  ${updatedCount}`);
  console.log(`   - Total in DB:     ${insertedCount + updatedCount}`);

  return { insertedCount, updatedCount };
}

// Support running both as standalone script and as Knex seed
if (require.main === module) {
  require('dotenv').config();
  seedShapes()
    .then(() => {
      console.log('🎉 Shapes Seeder completed without error.');
      process.exit(0);
    })
    .catch((err) => {
      console.error('❌ Seeder encountered an error:', err);
      process.exit(1);
    });
}

exports.seed = seedShapes;
