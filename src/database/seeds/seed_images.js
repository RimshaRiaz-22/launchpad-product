// ─── 4. SEEDER EXECUTION FUNCTION ─────────────────────────────────────────────
async function seedImages() {
  console.log('🚀 Starting Curated Stock & Mockup Images Seeding...');

  // 1. Ensure Asset Categories for Images
  console.log(`📂 Ensuring ${IMAGE_CATEGORIES.length} image categories...`);
  for (const cat of IMAGE_CATEGORIES) {
    const existing = await db('asset_categories').where({ id: cat.id }).first();
    if (!existing) {
      await db('asset_categories').insert({
        ...cat,
        created_at: db.fn.now(),
        updated_at: db.fn.now(),
      });
      console.log(`   ➕ Inserted image category: ${cat.name} (${cat.id})`);
    } else {
      await db('asset_categories')
        .where({ id: cat.id })
        .update({
          name: cat.name,
          label: cat.label,
          asset_type: cat.asset_type,
          description: cat.description,
          icon: cat.icon,
          color: cat.color,
          sort_order: cat.sort_order,
          is_active: cat.is_active,
          updated_at: db.fn.now(),
        });
    }
  }

  // 2. Ensure Subcategories for Images
  console.log(`📂 Ensuring ${IMAGE_SUBCATEGORIES.length} image subcategories...`);
  for (const sub of IMAGE_SUBCATEGORIES) {
    const existing = await db('asset_subcategories').where({ id: sub.id }).first();
    if (!existing) {
      await db('asset_subcategories').insert({
        ...sub,
        is_active: true,
        created_at: db.fn.now(),
        updated_at: db.fn.now(),
      });
      console.log(`   ➕ Inserted image subcategory: ${sub.name} (${sub.id})`);
    } else {
      await db('asset_subcategories')
        .where({ id: sub.id })
        .update({
          category_id: sub.category_id,
          name: sub.name,
          label: sub.label,
          sort_order: sub.sort_order,
          updated_at: db.fn.now(),
        });
    }
  }

  // 3. Batch upsert Images into `assets` table
  console.log(`✨ Upserting ${RAW_IMAGES_DATA.length} stock images into assets table in high-performance batches...`);
  let insertedCount = 0;
  let updatedCount = 0;

  // Process in chunks of 50 for rapid database execution over SSL
  const CHUNK_SIZE = 50;
  for (let i = 0; i < RAW_IMAGES_DATA.length; i += CHUNK_SIZE) {
    const chunk = RAW_IMAGES_DATA.slice(i, i + CHUNK_SIZE);
    
    for (const item of chunk) {
      const fileUrl = makeImageUrl(item.photoId);
      const existing = await db('assets').where({ id: item.id }).first();

      const assetPayload = {
        id: item.id,
        name: item.name,
        type: 'image',
        category: item.category,
        subcategory: item.subcategory,
        file_url: fileUrl,
        file_path: null,
        file_size: 280000,
        mime_type: 'image/jpeg',
        width: 1200,
        height: 800,
        is_builtin: true,
        is_premium: false,
        use_count: existing ? existing.use_count : 0,
        metadata: JSON.stringify({
          source: 'unsplash',
          photoId: item.photoId,
          tags: item.tags,
          format: 'jpg',
          aspect_ratio: '16:9',
        }),
        updated_at: db.fn.now(),
      };

      if (!existing) {
        await db('assets').insert({
          ...assetPayload,
          created_at: db.fn.now(),
        });
        insertedCount++;
      } else {
        await db('assets').where({ id: item.id }).update(assetPayload);
        updatedCount++;
      }
    }
    console.log(`   📦 Processed batch ${Math.floor(i / CHUNK_SIZE) + 1} (${Math.min(i + CHUNK_SIZE, RAW_IMAGES_DATA.length)} / ${RAW_IMAGES_DATA.length})...`);
  }

  // Invalidate memory cache so frontend immediately sees updated tree
  try {
    memoryCache.delPrefix('asset:categories');
  } catch (_) {}

  console.log(`✅ [Curated Stock Images] Seeding completed successfully!`);
  console.log(`   - Images Inserted: ${insertedCount}`);
  console.log(`   - Images Updated:  ${updatedCount}`);
  console.log(`   - Total in DB:     ${insertedCount + updatedCount}`);

  return { insertedCount, updatedCount };
}

// Support running both as standalone script and as Knex seed
if (require.main === module) {
  require('dotenv').config();
  seedImages()
    .then(() => {
      console.log('🎉 Images Seeder completed without error.');
      process.exit(0);
    })
    .catch((err) => {
      console.error('❌ Seeder encountered an error:', err);
      process.exit(1);
    });
}

exports.seed = seedImages;
